"""Builds the stylesheet of the "Classic view" of the protocol archive from the authentic earlier design.

    python website/tools/make_classic_css.py

Source: tools/source/classic-20261014/styles-20261014.css — the site stylesheet that was in production from
2026-10-14 to 2026-10-16 (identical to git 6d9497c `website/styles-20261014.css` and to the production backup
`site-20261016-before-premium.tgz`). Only the rules of the archive components are taken; their classes get the prefix
`c-` and every selector is scoped to `.archive-classic`, so the classic view cannot restyle the current design and the
current design's classes cannot leak into it. The old `:root` design tokens become properties of `.archive-classic`.
Output: website/archive-classic-<date>.css (new date when the output changes; Cloudflare caches 4 h).
"""
import hashlib
import pathlib
import re

TOOLS = pathlib.Path(__file__).resolve().parent
SOURCE = TOOLS / 'source' / 'classic-20261014' / 'styles-20261014.css'
OUT_NAME = 'archive-classic-20261118.css'
CLASSES = {
    'protocol-shell', 'protocol-map', 'protocol-map__heading', 'protocol-map__layer', 'protocol-map__layer-label',
    'protocol-map__links', 'protocol-content', 'page-hero', 'page-hero__title', 'page-hero__lead', 'page-hero__figure',
    'page-hero__figure--card', 'eyebrow', 'hero-actions', 'btn', 'btn--ghost', 'layer-nav', 'info-card', 'info-note',
    'layer-block', 'layer-block__head', 'layer-block__title', 'layer-block__text', 'layer-block__count',
    'layer-block__list', 'icon-badge', 'tag', 'tag--indigo', 'protocol-layer', 'protocol-layer__id',
    'protocol-layer__name', 'cta-band', 'release-line', 'icon',
}
ELEMENTS = {'a', 'h1', 'h2', 'h3', 'p', 'ul', 'li', 'code', 'details', 'summary', 'img', 'figure', 'time', '*'}
SCOPE = '.archive-classic'


def blocks(css):
    """Top-level (prelude, body) pairs; nested bodies stay raw."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        prelude, depth, k = css[i:j].strip(), 1, j + 1
        while k < n and depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        out.append((prelude, css[j + 1:k - 1]))
        i = k
    return out


def scope_part(part):
    part = part.strip()
    if not part or '#' in part:
        return None
    if part in (':root', 'body'):
        return SCOPE
    if part.startswith(('html', ':root', 'body ')):
        return None
    # ':not(:has(.x))' with a class the classic markup never contains is always true there: drop the condition.
    part = re.sub(r':not\(:has\(\.([A-Za-z0-9_-]+)\)\)', lambda m: '' if m.group(1) not in CLASSES else m.group(0), part)
    classes = re.findall(r'\.([A-Za-z0-9_-]+)', part)
    if classes:
        if any(c not in CLASSES for c in classes):
            return None
        part = re.sub(r'\.([A-Za-z0-9_-]+)', lambda m: '.c-' + m.group(1), part)
        return f'{SCOPE} {part}'
    head = re.split(r'[\s:>+~\[]', part)[0]
    if head in ELEMENTS:
        return f'{SCOPE} {part}'
    return None


def convert(css):
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith('@media'):
            inner = convert(body)
            if inner.strip():
                out.append(f'{prelude} {{\n{inner}}}\n')
            continue
        if prelude.startswith('@'):
            continue
        parts = [p for p in (scope_part(p) for p in prelude.split(',')) if p]
        if parts:
            decls = ' '.join(body.split())
            if prelude.strip() == 'body':
                decls = re.sub(r'min-height:[^;]+;?', '', decls)
            out.append(f'{", ".join(dict.fromkeys(parts))} {{ {decls} }}\n')
    return ''.join(out)


def build():
    raw = SOURCE.read_bytes()
    css = re.sub(r'/\*.*?\*/', '', raw.decode('utf-8'), flags=re.S)
    header = (f'/* Classic view of the protocol archive — generated by tools/make_classic_css.py from the design in '
              f'production 2026-10-14..16\n   (source sha256 {hashlib.sha256(raw).hexdigest()}). Do not edit by hand. */\n')
    local = """
/* Container: the classic page background and type, and neutralising the current design inside it. */
.archive-classic { display: block; background: var(--bg-deep); color: var(--text-primary); font-family: var(--font-ui); line-height: 1.65;
  padding-block: 2.5rem 4rem; }
.archive-classic[hidden] { display: none; }
.archive-classic :where(h1, h2, h3, p, a, li, summary) { letter-spacing: normal; text-transform: none; }
.archive-classic .c-icon { width: 1.1em; height: 1.1em; flex: none; }
.archive-classic .c-classic-search { display: flex; flex-wrap: wrap; gap: .6rem; align-items: center; margin: 0 0 1.4rem; }
.archive-classic .c-classic-search input { flex: 1 1 16rem; min-height: 44px; padding: .55rem .9rem; border: 1px solid var(--border-strong);
  border-radius: 12px; background: var(--bg-card); color: var(--text-primary); font: inherit; }
.archive-classic .c-classic-search input:focus-visible, .archive-classic .c-classic-search select:focus-visible { outline: 3px solid var(--primary); outline-offset: 2px; }
.archive-classic .c-classic-search select { min-height: 44px; padding: .5rem 2rem .5rem .9rem; border: 1px solid var(--border-strong); border-radius: 12px;
  background: var(--bg-card); color: var(--text-primary); font: inherit; max-width: 100%; }
.archive-classic .c-classic-search output { color: var(--text-muted); font-size: .9rem; }
.archive-classic .c-layer-nav a[aria-pressed="true"] { background: var(--primary); color: #fff; border-color: var(--primary); }
.archive-classic .c-classic-empty { color: var(--text-secondary); }
.archive-classic a:focus-visible, .archive-classic summary:focus-visible { outline: 3px solid var(--primary); outline-offset: 2px; }
"""
    return header + convert(css) + local


def main():
    out = TOOLS.parent / OUT_NAME
    out.write_text(build(), encoding='utf-8', newline='\n')
    print('wrote', out, out.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
